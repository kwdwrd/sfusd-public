    for name, lottery in [('Base', 'baseline'), ('Cap', 'capacity')]:
        a = model_a.loc[lottery]
        m.add(f'numProbitSlope{name}', f(a.b_r, 3), f'risk_aversion_estimates.csv: Model A b_r, {lottery}')
        m.add(f'numProbitSlope{name}SE', f(a.b_r_se, 3), f'risk_aversion_estimates.csv: Model A b_r_se, {lottery}')
        m.add(f'numSigmaBound{name}', f(a.sigma_lower_bound_95, 0),
              f'risk_aversion_estimates.csv: Model A sigma_lower_bound_95, {lottery}')
        m.add(f'numRiskDesigns{name}', str(int(a.n_designs)),
              f'risk_aversion_estimates.csv: Model A n_designs, {lottery}')
        m.add(f'numRiskDropped{name}', str(int(a.n_dropped_dominance)),
              f'risk_aversion_estimates.csv: Model A n_dropped_dominance, {lottery}')

    rows = [
        f'CARA $\\hat r$ (per $\\theta$ unit), $\\mu = 1$ & ${b.r_theta:.2f}$ (${b.r_theta_se:.2f}$) & '
        f'${c.r_theta:.2f}$ (${c.r_theta_se:.2f}$) \\\\',
        f'Lottery mean / s.d. & ${b.lottery_mean:.2f}$ / ${b.lottery_sd:.2f}$ & ${c.lottery_mean:.2f}$ / ${c.lottery_sd:.2f}$ \\\\',
        f'Certainty equivalent & ${b.certainty_equivalent:.2f}$ & ${c.certainty_equivalent:.2f}$ \\\\',
        f'Risk premium (= $\\hat c$) & ${b.risk_premium:.2f}$ & ${c.risk_premium:.2f}$ \\\\',
        f'Risk premium / lottery s.d. & ${b.risk_premium_per_sd:.2f}$ & ${c.risk_premium_per_sd:.2f}$ \\\\',
        f'Probability of an outcome below the CE & ${sci(b.prob_below_ce)}$ & ${c.prob_below_ce:.3f}$ \\\\',
        f'$\\hat r$ after dropping lowest 1 / 3 outcomes & ${b.r_drop_lowest_1:.0f}$ / ${b.r_drop_lowest_3:.0f}$ & '
        f'${c.r_drop_lowest_1:.1f}$ / ${c.r_drop_lowest_3:.0f}$ \\\\',
        f'Premium as share of maximum & ${b.premium_share_of_max:.2f}$ & ${c.premium_share_of_max:.2f}$ \\\\',
        f'Holt--Laury-equivalent CRRA $\\rho$ & ${b.holt_laury_equivalent_crra:.2f}$ & ${c.holt_laury_equivalent_crra:.2f}$ \\\\',
        f'Implied CRRA if $\\theta$ unit $= \\$50$k, $W = \\$1$M & ${b.crra_if_theta_worth_50000:.0f}$ & '
        f'${c.crra_if_theta_worth_50000:.0f}$ \\\\',
        f'$\\$$ per $\\theta$ unit needed for $\\rho = 2$, $W = \\$1$M & ${dollars_m(b[breakeven])}$ & '
        f'${dollars_m(c[breakeven])}$ \\\\',
        f'Model A (heterogeneous $r_i$): probit slope on $r^*_k$ & ${model_a.loc["baseline"].b_r:.3f}$ '
        f'(${model_a.loc["baseline"].b_r_se:.3f}$) & ${model_a.loc["capacity"].b_r:.3f}$ '
        f'(${model_a.loc["capacity"].b_r_se:.3f}$) \\\\',
    ]
    write_table('risk_aversion', rows)

    # Applicant and request totals quoted in §application-effects. Both were
    # hand-typed; the request totals come from the balanced 70-school panel, so
    # they exclude Mission Education Center (the one undersubscribed school).
    fr_all = pd.read_csv(OUT / 'first_rankings_by_year.csv').set_index('ay')
    m.add('numApplicantsPrev', count(float(fr_all.loc['24-25', 'all_first_rankings'])),
          'first_rankings_by_year.csv: all_first_rankings, 24-25')
    summ = pd.read_csv(OUT / 'application_effects_summary.csv')
    for label, col in [('Prev', 'num_requests_24-25'), ('Now', 'num_requests_25-26')]:
        total = (summ[col] * summ.n_schools).sum()
        m.add(f'numRequests{label}', count(total),
              f'application_effects_summary.csv: {col} x n_schools, summed over groups')

    # Collinearity among the candidate quality measures (§promotion-rates): the
    # text quoted a hand-typed |rho| range that omitted the ELA-math pair.
    pr = pd.read_csv(OUT / 'promotion_rates.csv')
    corr_cols = ['theta', 'sbac_ela', 'sbac_math', 'unduplicated_share']
    cm = pr[corr_cols].corr().abs()
    pairs = [cm.iloc[i, j] for i in range(len(corr_cols)) for j in range(i + 1, len(corr_cols))]
    m.add('numRhoMin', f(min(pairs)), 'promotion_rates.csv: smallest pairwise |corr| among quality measures')
    m.add('numRhoMax', f(max(pairs)), 'promotion_rates.csv: largest pairwise |corr| among quality measures')

    # Roster eligibility against the CDE TK census (§promotion-rates).
    diff = (pr.promotion_eligible - pr.cde_tk_2425).abs().dropna()
    m.add('numCdeMatchWithinTwo', str(int((diff <= 2).sum())),
          'promotion_rates.csv: schools with |promotion_eligible - cde_tk_2425| <= 2')
    m.add('numCdeMatchMaxDiff', str(int(diff.max())),
          'promotion_rates.csv: largest |promotion_eligible - cde_tk_2425|')

    # Quality drift between the main window and the full panel (§quality-over-time).
    main_theta = pd.read_csv(OUT / 'school_quality_estimates.csv').set_index('school_name').theta
    panel = pd.read_csv(OUT / 'school_quality_full_panel.csv').set_index('school_name').theta
    both = pd.concat([main_theta.rename('main'), panel.rename('panel')], axis=1).dropna()
    # Each normalization differs, so compare mean-centered values.
    drift = (both.main - both.main.mean()) - (both.panel - both.panel.mean())
    src_q = 'school_quality_estimates.csv vs school_quality_full_panel.csv'
    m.add('numMoverUpMax', f(drift.max()), f'{src_q}: largest rise in the recent window')
    m.add('numMoverUpSchool', drift.idxmax(), f'{src_q}: school with the largest rise')
    m.add('numMoverDownMax', f(-drift.min()), f'{src_q}: largest fall (reported positive)')
    m.add('numMoverDownSchool', drift.idxmin(), f'{src_q}: school with the largest fall')
    m.add('numMoversAboveTwoTenths', str(int((drift.abs() > 0.2).sum())),
          f'{src_q}: schools moving more than 0.2 either way')

    # The introduction's enrollment-revenue counterfactual (lcff_counterfactual.py).
    lc = pd.read_csv(OUT / 'lcff_counterfactual.csv').set_index('key').value
    src = 'lcff_counterfactual.csv'
    m.add('numSfusdEnrollment', count(float(lc.sfusd_enrollment)), f'{src}: sfusd_enrollment')
    m.add('numPrivateStudents', count(float(lc.private_students_now)), f'{src}: private_students_now')
    m.add('numPrivateShare', pct(float(lc.sf_private_share)), f'{src}: sf_private_share')
    m.add('numNationalPrivateShare', pct(float(lc.national_private_share)), f'{src}: national_private_share')
    m.add('numStudentsGained', count(float(lc.students_gained)), f'{src}: students_gained')
    m.add('numAdaGained', count(float(lc.ada_gained)), f'{src}: ada_gained')
    m.add('numUPP', pct(float(lc.upp), 1), f'{src}: upp')
    m.add('numUPPthreshold', pct(float(lc.upp_threshold)), f'{src}: upp_threshold')
    m.add('numUPPafter', pct(float(lc.upp_after), 1), f'{src}: upp_after')
    m.add('numLcffGain', f'\\${float(lc.lcff_gain) / 1e6:.0f} million', f'{src}: lcff_gain')
    m.add('numLcffNaiveGain', f'\\${float(lc.naive_gain_at_average_rate) / 1e6:.0f} million',
          f'{src}: naive_gain_at_average_rate')
    m.add('numLcffModelError',
          pct(abs(float(lc.lcff_modelled_per_ada) / float(lc.lcff_actual_per_ada) - 1.0), 0),
          f'{src}: |modelled/actual LCFF per ADA - 1|')
    m.add('numLcffPerAda', f'\\${float(lc.lcff_actual_per_ada):,.0f}'.replace(',', '{,}'),
          f'{src}: lcff_actual_per_ada')

    val = pd.read_csv(OUT / 'risk_aversion_validation.csv').set_index('check')
    src = 'risk_aversion_validation.csv'
    m.add('numValChecks', str(len(val)), f'{src}: rows')
    m.add('numValPassing', 'all passing' if val.passed.all() else f'{int(val.passed.sum())} passing',
          f'{src}: passed')

    def number(check):
        return float(re.findall(r'[-\d.]+(?= \(true|$)', val.loc[check, 'detail'])[0])
    m.add('numValMeanM', f(number('Model A mean m'), 3), f'{src}: Model A mean m')
    m.add('numValMeanSigma', f(number('Model A mean sigma'), 3), f'{src}: Model A mean sigma')
    m.add('numValCoverM', f(number('Model A coverage m')), f'{src}: Model A coverage m')
    m.add('numValCoverSigma', f(number('Model A coverage sigma')), f'{src}: Model A coverage sigma')


