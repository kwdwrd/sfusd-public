#!/usr/bin/env python3
"""
Write every number the paper reports to LaTeX, so main.tex never contains a
hand-typed result.

Reads only the CSVs in output/ (it never re-estimates anything) and writes:
  output/numbers.tex        \\newcommand macros for numbers quoted in the text
  output/tables/*.tex       tabular bodies for the paper's tables

main.tex does \\input{output/numbers.tex} in its preamble and \\input's each
table body. Every macro is named \\num<Something> and carries a comment naming
its source CSV and column. run_distaste_analysis.py calls main() at the end of
a run; it can also be run on its own: `python3 make_numbers.py`.
"""

import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

sys.path.insert(0, 'src')
from distaste import gap_as_school_pair

OUT = Path('output')
TABLES = OUT / 'tables'


# ---------------------------------------------------------------- formatting

def f(x, digits=2):
    """Fixed-point, with a true minus sign usable in or out of math mode."""
    s = f'{x:.{digits}f}'
    return s.replace('-', '\\ensuremath{-}') if s.startswith('-') else s


def pct(x, digits=0, signed=False):
    s = f'{100 * x:+.{digits}f}' if signed else f'{100 * x:.{digits}f}'
    return s.replace('-', '\\ensuremath{-}') + '\\%'


def count(x):
    """Integer with a LaTeX thousands separator, e.g. 3{,}981."""
    return f'{int(round(x)):,}'.replace(',', '{,}')


def sci(x):
    """1 significant figure scientific notation, e.g. 5 \\times 10^{-7}."""
    mantissa, exponent = f'{x:.0e}'.split('e')
    return f'\\ensuremath{{{mantissa} \\times 10^{{{int(exponent)}}}}}'


def dollars_m(x):
    return f'\\${x / 1e6:.1f}M'


def stars(p):
    return '^{***}' if p < 0.01 else '^{**}' if p < 0.05 else '^{*}' if p < 0.10 else ''


def cell(coef, se, p):
    return f'${coef:.3f}{stars(p)}$ (${se:.3f}$)'


class Macros:
    def __init__(self):
        self.lines = []
        self.names = set()

    def add(self, name, value, source):
        assert re.fullmatch(r'num[A-Za-z]+', name), f'bad macro name {name}'
        assert name not in self.names, f'duplicate macro {name}'
        self.names.add(name)
        self.lines.append(f'\\newcommand{{\\{name}}}{{{value}}}  % {source}')

    def write(self, path):
        header = ('% Generated by make_numbers.py from output/*.csv. Do not edit by hand;\n'
                  '% rerun `python3 make_numbers.py` (or the full pipeline) instead.\n')
        path.write_text(header + '\n'.join(self.lines) + '\n')


def write_table(name, rows):
    TABLES.mkdir(exist_ok=True)
    header = f'% Generated by make_numbers.py; do not edit by hand.\n'
    (TABLES / f'{name}.tex').write_text(header + '\n'.join(rows) + '\n')


