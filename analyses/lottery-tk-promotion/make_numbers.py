def school_gap(m, name, school_theta, gap, source):
    """Name and citywide rank of the school `gap` theta-units below the top school."""
    ordered = school_theta.sort_values('theta', ascending=False).reset_index(drop=True)
    _, _, match_name, _, _ = gap_as_school_pair(school_theta, gap, 'top')
    rank = int(ordered.index[ordered.school_name == match_name][0]) + 1
    m.add(f'num{name}School', match_name, f'{source}; gap_as_school_pair on school_quality_estimates.csv')
    m.add(f'num{name}Rank', str(rank), f'{source}; rank of that school by theta')


def quality_and_lottery(m):
    summary = pd.read_csv(OUT / 'lottery_distaste_summary.csv', index_col=0)['value']
    theta = pd.read_csv(OUT / 'school_quality_estimates.csv')
    admission = pd.read_csv(OUT / 'school_admission_probabilities.csv')
    robust = pd.read_csv(OUT / 'robustness_quality_measurement.csv')
    main = robust.iloc[0]
    src = 'lottery_distaste_summary.csv'

    m.add('numSchools', str(int(main.n_schools)), 'robustness_quality_measurement.csv: main n_schools')
    m.add('numEUbase', f(summary.expected_value_weighted), f'{src}: expected_value_weighted')
    m.add('numEUcap', f(summary.expected_value_capacity), f'{src}: expected_value_capacity')
    m.add('numEUgap', f(summary.expected_value_weighted - summary.expected_value_capacity),
          f'{src}: expected_value_weighted - expected_value_capacity')

    top = theta.sort_values('theta', ascending=False).iloc[0]
    m.add('numTopSchool', top.school_name, 'school_quality_estimates.csv: highest theta')
    m.add('numTopTheta', f(top.theta), 'school_quality_estimates.csv: highest theta')

    low = admission.loc[admission.admission_prob.idxmin()]
    m.add('numAdmitMinSchool', low.school_name.replace(' ES', ''), 'school_admission_probabilities.csv: min admission_prob')
    m.add('numAdmitMin', pct(low.admission_prob, 1), 'school_admission_probabilities.csv: min admission_prob')
    m.add('numAdmitTop', pct(admission.set_index('school_name').loc[top.school_name, 'admission_prob'], 1),
          'school_admission_probabilities.csv: admission_prob of the top school')
    m.add('numAdmitMedian', pct(admission.admission_prob.median()), 'school_admission_probabilities.csv: median')
    m.add('numUndersubscribed', str(int((admission.admission_prob >= 1).sum())),
          'school_admission_probabilities.csv: admission_prob == 1')

    # Baseline formula: probability of landing in the top k schools, and their seats
    ordered = admission.sort_values('theta', ascending=False)
    p = ordered.admission_prob.clip(upper=1).to_numpy()
    reach = p * np.concatenate([[1], np.cumprod(1 - p)[:-1]])
    m.add('numReachTopEight', f(reach[:8].sum()), 'school_admission_probabilities.csv: baseline P(top 8)')
    m.add('numReachTopFifteen', f(reach[:15].sum()), 'school_admission_probabilities.csv: baseline P(top 15)')
    seats8 = ordered.capacity.iloc[:8].sum()
    m.add('numSeatsTopEight', count(round(seats8, -1)), 'school_admission_probabilities.csv: capacity of top 8, to nearest 10')
    m.add('numSeatsTopEightShare', pct(seats8 / summary.simulation_n_families),
          'top-8 capacity / simulation_n_families')

    m.add('numAboveEUbase', str(int(main.schools_above_eu)), 'robustness_quality_measurement.csv: main schools_above_eu')
    m.add('numAboveEUcap', str(int(main.schools_above_eu_capacity)),
          'robustness_quality_measurement.csv: main schools_above_eu_capacity')

    m.add('numCohort', count(summary.simulation_n_families), f'{src}: simulation_n_families')
    m.add('numSeats', count(summary.simulation_total_seats), f'{src}: simulation_total_seats')
    m.add('numSimPlaced', pct(summary.simulation_share_placed_from_list), f'{src}: simulation_share_placed_from_list')
    m.add('numSimAdmin', pct(summary.simulation_share_administrative), f'{src}: simulation_share_administrative')
    m.add('numSimNoSeat', pct(summary.simulation_share_no_seat), f'{src}: simulation_share_no_seat')

    m.add('numFOVbase', f(summary.distaste_weighted_mean_family_weighted), f'{src}: distaste_weighted_mean_family_weighted')
    m.add('numFOVcap', f(summary.distaste_capacity_mean_family_weighted), f'{src}: distaste_capacity_mean_family_weighted')
    school_gap(m, 'FOVbase', theta, summary.distaste_weighted_mean_family_weighted, src)
    school_gap(m, 'FOVcap', theta, summary.distaste_capacity_mean_family_weighted, src)

    m.add('numChat', f(summary.certainty_premium_pooled), f'{src}: certainty_premium_pooled')
    m.add('numChatSE', f(summary.certainty_premium_pooled_se), f'{src}: certainty_premium_pooled_se')
    m.add('numChatCap', f(summary.certainty_premium_capacity_pooled), f'{src}: certainty_premium_capacity_pooled')
    m.add('numChatCapSE', f(summary.certainty_premium_capacity_pooled_se), f'{src}: certainty_premium_capacity_pooled_se')
    m.add('numReqPerApplicant', f(summary.simulation_target_list_length),
          f'{src}: simulation_target_list_length (the list length the simulation calibrates to)')
    school_gap(m, 'Chat', theta, summary.certainty_premium_pooled, src)
    school_gap(m, 'ChatCap', theta, summary.certainty_premium_capacity_pooled, src)
    school_gap(m, 'OneUnit', theta, 1.0, 'one theta unit')

    m.add('numBetaFree', f(summary.free_slope_beta), f'{src}: free_slope_beta')
    m.add('numBetaFreeSE', f(summary.free_slope_beta_se), f'{src}: free_slope_beta_se')


def promotion(m):
    rates = pd.read_csv(OUT / 'promotion_rates.csv')
    src = 'promotion_rates.csv'
    eligible, accepted = rates.promotion_eligible.sum(), rates.promotion_accepted.sum()
    m.add('numEligibleBuildings', str(len(rates)), f'{src}: rows')
    m.add('numEligibleFamilies', count(eligible), f'{src}: sum promotion_eligible')
    m.add('numPromoted', count(accepted), f'{src}: sum promotion_accepted')
    m.add('numNonAccepting', count(eligible - accepted),
          f'{src}: sum promotion_eligible - sum promotion_accepted')
    m.add('numTakeup', pct(accepted / eligible), f'{src}: pooled promotion rate')
    m.add('numRateMin', pct(rates.promotion_rate.min()), f'{src}: min promotion_rate')
    m.add('numRateMax', pct(rates.promotion_rate.max()), f'{src}: max promotion_rate')

    negative_base = rates[rates.distaste_weighted < 0]
    negative_cap = rates[rates.distaste_weighted_capacity < 0]
    m.add('numNegFOVbaseSchools', str(len(negative_base)), f'{src}: distaste_weighted < 0')
    m.add('numNegFOVcapSchools', str(len(negative_cap)), f'{src}: distaste_weighted_capacity < 0')
    m.add('numNegFOVcapFamilies', count(negative_cap.promotion_accepted.sum()),
          f'{src}: promotion_accepted where distaste_weighted_capacity < 0')

    for name, col in [('Theta', 'theta'), ('ELA', 'sbac_ela'), ('Math', 'sbac_math'),
                      ('Unduplicated', 'unduplicated_share')]:
        d = rates[['promotion_rate', col]].dropna()
        rho, p = stats.pearsonr(d.promotion_rate, d[col])
        m.add(f'numCorrRate{name}', f(rho), f'{src}: corr(promotion_rate, {col})')
        if name == 'Unduplicated':
            m.add('numCorrRateUnduplicatedP', f(p), f'{src}: p-value of corr(promotion_rate, {col})')


def application_effects(m):
    summary = pd.read_csv(OUT / 'application_effects_summary.csv').set_index('group')
    did = pd.read_csv(OUT / 'application_effects_did.csv')
    model = pd.read_csv(OUT / 'application_effects_model.csv')
    lottery = pd.read_csv(OUT / 'lottery_distaste_summary.csv', index_col=0)['value']
    eligible, other = summary.loc['Promotion-eligible'], summary.loc['Other schools']

    m.add('numApplicantsTreat', count(lottery.simulation_n_families - lottery.n_families_weighted),
          'lottery_distaste_summary.csv: simulation_n_families - n_families_weighted')
    m.add('numCommonEffect', f(-model.common_effect_all_schools.iloc[0]),
          'application_effects_model.csv: -common_effect_all_schools')
    first = model[model.outcome == 'First-choice requests'].set_index('spec')
    allr = model[model.outcome == 'All ranked requests'].set_index('spec')
    m.add('numPredAllQone', f(allr.predicted_did_q1.iloc[0]), 'application_effects_model.csv: predicted_did_q1, all ranked')
    m.add('numPredFirstQone', f(first.predicted_did_q1.iloc[0]), 'application_effects_model.csv: predicted_did_q1, first choice')
    m.add('numPredAllQoneAbs', f(-allr.predicted_did_q1.iloc[0]), 'application_effects_model.csv: -predicted_did_q1, all ranked')

    m.add('numDidEligible', str(int(eligible.n_schools)), 'application_effects_summary.csv: n_schools')
    m.add('numDidOther', str(int(other.n_schools)), 'application_effects_summary.csv: n_schools')
    m.add('numDidSchools', str(int(eligible.n_schools + other.n_schools)), 'application_effects_summary.csv: n_schools')
    m.add('numFirstEligibleBefore', f(eligible['num_first_choice_24-25'], 1), 'application_effects_summary.csv')
    m.add('numFirstEligibleAfter', f(eligible['num_first_choice_25-26'], 1), 'application_effects_summary.csv')
    m.add('numAllChangeEligible', pct(-eligible.num_requests_change_24_25), 'application_effects_summary.csv: -change')
    m.add('numAllChangeOther', pct(-other.num_requests_change_24_25), 'application_effects_summary.csv: -change')
    m.add('numPromotedShareFirst', f(eligible.intensity_first_choice_mean), 'application_effects_summary.csv')
    m.add('numPromotedShareAll', f(eligible.intensity_requests_mean), 'application_effects_summary.csv')

    def row(outcome, spec_prefix, method, term):
        r = did[(did.outcome == outcome) & did.spec.str.startswith(spec_prefix)
                & (did.method == method) & (did.term == term)]
        assert len(r) == 1, (outcome, spec_prefix, method, term)
        return r.iloc[0]

    first_2x2 = row('First-choice requests', '2x2', 'OLS', 'treated:post_25')
    first_trend = row('First-choice requests', 'Pooled pre-period + group', 'OLS', 'treated:post_25')
    m.add('numDidFirstTwo', f(first_2x2.coef), 'application_effects_did.csv: first choice, 2x2, OLS')
    m.add('numDidFirstTwoPct', pct(-first_2x2.pct_effect), 'application_effects_did.csv: first choice, 2x2, OLS pct_effect')
    m.add('numDidFirstTrend', f(first_trend.coef), 'application_effects_did.csv: first choice, trend, OLS')
    m.add('numImpliedFTwo', f(first.implied_q.iloc[0]), 'application_effects_model.csv: implied_q, first, 2x2')
    m.add('numImpliedFTrend', f(first.implied_q.iloc[2]), 'application_effects_model.csv: implied_q, first, trend')
    all_ranks = model[model.outcome == 'All ranked requests']
    m.add('numImpliedQMin', f(all_ranks.implied_q.min()),
          'application_effects_model.csv: implied_q, all ranked, min across specs')
    m.add('numImpliedQMax', f(all_ranks.implied_q.max()),
          'application_effects_model.csv: implied_q, all ranked, max across specs')

    # The abstract's first-choice claim holds only if enough promoted families
    # would have ranked their own school first; below this f the eligible-vs-other
    # comparison flips sign. Solves
    #   ln((elig_obs + f*promoted)/elig_prev) = ln(other_now/other_prev).
    fr = pd.read_csv(OUT / 'first_rankings_by_year.csv').set_index('ay')
    src_fr = 'first_rankings_by_year.csv'
    prev, now = '24-25', '25-26'
    promoted_n = fr.loc[now, 'eligible_plus_promoted'] - fr.loc[now, 'eligible']
    f_breakeven = (fr.loc[prev, 'eligible'] * (fr.loc[now, 'other'] / fr.loc[prev, 'other'])
                   - fr.loc[now, 'eligible']) / promoted_n
    m.add('numFBreakeven', f(f_breakeven), f'{src_fr}: f at which the eligible-vs-other first-choice DiD is zero')
    m.add('numEligiblePlusPromoted', count(fr.loc[now, 'eligible_plus_promoted']),
          f'{src_fr}: eligible first choices plus promoted families, {now}')
    all_ols = did[(did.outcome == 'All ranked requests') & (did.method == 'OLS') & (did.term == 'treated:post_25')]
    m.add('numDidAllMin', f(all_ols.coef.max()), 'application_effects_did.csv: all ranked, OLS post_25, smallest effect')
    m.add('numDidAllMax', f(all_ols.coef.min()), 'application_effects_did.csv: all ranked, OLS post_25, largest effect')
    for name, outcome, method in [('IntensityFirst', 'First-choice requests', 'OLS'),
                                  ('IntensityFirstPPML', 'First-choice requests', 'PPML'),
                                  ('IntensityAll', 'All ranked requests', 'OLS')]:
        r = row(outcome, 'Model intensity', method, 'model_effect:post_25')
        m.add(f'num{name}', f(r.coef), f'application_effects_did.csv: {outcome}, model intensity, {method}')
        if name == 'IntensityAll':
            m.add('numIntensityAllSE', f(r.se), 'application_effects_did.csv: all ranked, model intensity, OLS se')

    # Table: summary statistics
    def cols(stat):
        return f'{eligible[stat]:.1f} & {other[stat]:.1f}'
    rows = [f'Schools & {int(eligible.n_schools)} & {int(other.n_schools)} \\\\']
    for label, prefix in [('All ranked requests', 'num_requests'), ('First-choice requests', 'num_first_choice')]:
        rows.append(f'\\multicolumn{{3}}{{l}}{{\\emph{{{label}, mean per school}}}} \\\\')
        rows.append(f'\\quad 2021--22 to 2024--25 average & {cols(prefix + "_pre_mean")} \\\\')
        for ay, label_ay in [('24-25', '2024--25'), ('25-26', '2025--26'), ('26-27', '2026--27')]:
            rows.append(f'\\quad {label_ay} & {cols(f"{prefix}_{ay}")} \\\\')
        change = f'{prefix}_change_24_25'
        rows.append(f'\\quad Change, 2024--25 to 2025--26 & ${100 * eligible[change]:+.0f}\\%$ & '
                    f'${100 * other[change]:+.0f}\\%$ \\\\')
    rows.append(f'Promoted families per school, 2025--26 & {eligible.promoted_per_school:.1f} & --- \\\\')
    rows.append(f'Promoted / 2024--25 requests (all ranks; first choice) & {eligible.intensity_requests_mean:.2f}; '
                f'{eligible.intensity_first_choice_mean:.2f} & --- \\\\')
    write_table('application_summary', rows)

    # Table: difference-in-differences
    specs = ['2x2', 'Pooled pre-period (', 'Pooled pre-period + group', 'Model intensity']
    rows = []
    for outcome, label in [('First-choice requests', 'First-choice requests'), ('All ranked requests', 'All ranked requests')]:
        rows.append(f'\\multicolumn{{5}}{{l}}{{\\emph{{{label}}}}} \\\\')
        for method in ['OLS', 'PPML']:
            cells = [cell(*row(outcome, s, method, 'treated:post_25')[['coef', 'se', 'p']]) for s in specs[:3]]
            rows.append(f'\\quad Eligible $\\times$ 2025--26, {method} & ' + ' & '.join(cells) + ' & --- \\\\')
        r = row(outcome, 'Model intensity', 'OLS', 'model_effect:post_25')
        rows.append(f'\\quad Model-predicted effect $\\times$ 2025--26, OLS & --- & --- & --- & {cell(r.coef, r.se, r.p)} \\\\')
        cells = [cell(*row(outcome, s, 'OLS', 'treated:post_26')[['coef', 'se', 'p']]) for s in specs[1:]]
        rows.append('\\quad Eligible $\\times$ 2026--27, OLS & --- & ' + ' & '.join(cells) + ' \\\\')
        implied = model[model.outcome == outcome].implied_q
        rows.append('\\quad Implied $q$ (all ranks) or $f$ (first choice) & '
                    + ' & '.join(f'${q:.2f}$' for q in implied) + ' & --- \\\\')
    write_table('application_did', rows)


def robustness(m):
    robust = pd.read_csv(OUT / 'robustness_quality_measurement.csv')
    src = 'robustness_quality_measurement.csv'
    for name, col in [('FOVbase', 'forgone_value'), ('FOVcap', 'forgone_value_capacity'),
                      ('Chat', 'certainty_premium'), ('ChatCap', 'certainty_premium_capacity'),
                      ('BetaFreeSE', 'free_slope_beta_se')]:
        m.add(f'numRob{name}Min', f(robust[col].min()), f'{src}: min {col}')
        m.add(f'numRob{name}Max', f(robust[col].max()), f'{src}: max {col}')

    labels = {
        'Main: pooled': 'Main: pooled, 2021--22 to 2024--25',
        'Pooled, full panel': 'Pooled, full panel (2012--13 to 2026--27)',
        'Pooled, 21-22 to 25-26': 'Pooled, 2021--22 to 2025--26',
    }
    rows = []
    for r in robust.itertuples():
        label = next((v for k, v in labels.items() if r.spec.startswith(k)), None)
        if label is None:
            yy = r.spec.split(', ')[1]
            label = f'Single year, 20{yy[:2]}--{yy[3:]}'
        values = [r.forgone_value, r.forgone_value_capacity, r.certainty_premium, r.certainty_premium_capacity,
                  r.free_slope_beta, r.corr_rate_theta]
        rows.append(f'{label} & ' + ' & '.join(f'${v:.2f}$' for v in values) + ' \\\\')
    write_table('robustness', rows)

    corr = pd.read_csv(OUT / 'quality_rank_correlation_by_year.csv', index_col=0)
    with_main = pd.read_csv(OUT / 'quality_rank_correlation_with_main.csv').set_index('ay')
    adjacent = np.diag(corr.values, k=-1)
    src = 'quality_rank_correlation_by_year.csv'
    m.add('numRankAdjMin', f(adjacent.min()), f'{src}: min adjacent-year correlation')
    m.add('numRankAdjMax', f(adjacent.max()), f'{src}: max adjacent-year correlation')
    m.add('numRankFirstLast', f(corr.iloc[-1, 0]), f'{src}: first vs. last cycle')
    src = 'quality_rank_correlation_with_main.csv'
    m.add('numRankNineteen', f(with_main.loc['19-20', 'spearman']), f'{src}: 19-20')
    neighbors = with_main.loc[['18-19', '20-21'], 'spearman']
    m.add('numRankNineteenNbrMin', f(neighbors.min()), f'{src}: 18-19 and 20-21')
    m.add('numRankNineteenNbrMax', f(neighbors.max()), f'{src}: 18-19 and 20-21')
    m.add('numRankWindowMin', f(with_main.loc[['21-22', '22-23', '23-24', '24-25'], 'spearman'].min()),
          f'{src}: min over main window')
    m.add('numRankPostMin', f(with_main.loc[['25-26', '26-27'], 'spearman'].min()), f'{src}: min over 25-26, 26-27')


